import assert from 'node:assert/strict';
import test from 'node:test';
import {fileURLToPath} from 'node:url';
import {mkdir} from 'node:fs/promises';
import {build,preview} from 'vite';
import {chromium} from 'playwright';

test('动态页 LoRA 覆盖、关闭、保存重读、恢复继承与移动布局',async t=>{
  const output=fileURLToPath(new URL('../../../Saved/Tests/video-loras/',import.meta.url));
  await mkdir(output,{recursive:true});
  const config={root:fileURLToPath(new URL('../../',import.meta.url)),build:{outDir:output+'dist',emptyOutDir:false,rollupOptions:{input:{main:fileURLToPath(new URL('./video-loras.html',import.meta.url))}}},logLevel:'error'};
  await build(config);
  const server=await preview({...config,preview:{host:'127.0.0.1',port:0}});
  t.after(()=>new Promise(resolve=>server.httpServer.close(resolve)));
  const browser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL||(process.platform==='win32'?'msedge':undefined)});
  t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1400,height:1000}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  let document={text:'树叶在微风中摇动。',composition:'standalone',duration:4,loop:true,quality:'standard',steps:20,reference_images:[]};
  const saved=[];
  const resource={id:'lora-'+ 'b'.repeat(16),name:'H3 测试 LoRA',file:{relative_path:'loras/leaf.safetensors',sha256:'b'.repeat(64),size_bytes:1},architecture:{family:'minimax-h3',prompt_family:'minimax-h3'},base_models:[{name:'MiniMax H3'}],activation:{trigger_words:['leaf_motion'],tags:[]},recommended_generation:{weight:{default:.4,minimum:null,maximum:null,status:'untested'},status:'untested'},description:'测试资源',source:{type:'local_file'},previews:[],examples:[]};
  await page.route('**/api/**',route=>route.fulfill({json:{}}));
  await page.route('**/api/agent/page-editor',route=>route.fulfill({json:{document:{},save:{args:{project_id:'demo',page_key:{page_id:'page-video'},section:'content',expected_sha256:'content'}}}}));
  await page.route('**/api/agent/prompt/read',route=>route.fulfill({json:{document,save:{args:{project_id:'demo',target:{kind:'page',id:'page-video'},expected_sha256:'prompt',source_versions:{}}}}}));
  await page.route('**/api/agent/prompt/save',route=>{const request=route.request().postDataJSON();saved.push(request);document=structuredClone(request.changes);return route.fulfill({json:{saved:true}});});
  await page.route('**/workbench/video-source',route=>route.fulfill({json:{sources:[],source_page_key:null,revision:'revision'}}));
  await page.route('**/workbench/page-media',route=>route.fulfill({json:{media:{candidates:[]},revision:'revision'}}));
  await page.route('**/api/lora-resources',route=>route.fulfill({json:{resources:[{resource,status:'available',storage:'local'},{resource:{...resource,id:'lora-'+ 'c'.repeat(16),name:'Anima 测试 LoRA',architecture:{family:'anima',prompt_family:'anima'}},status:'available',storage:'local'}],raw:[],errors:[]}}));
  await page.route('**/api/projects/demo/render-profile',route=>route.fulfill({json:{current_profile_id:'anima-base-v1',render_profiles:[{id:'minimax-h3',architecture_family:'minimax-h3'},{id:'anima-base-v1',architecture_family:'anima'}]}}));
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/tests/browser/video-loras.html`);
  const editor=page.getByRole('region',{name:'本页 LoRA',exact:true});
  const inherited=editor.locator('details').filter({has:page.locator('summary').filter({hasText:'继承的项目 LoRA'})});
  await inherited.locator('summary').click();
  assert.equal(await inherited.getByRole('spinbutton').inputValue(),'0.6');
  await inherited.getByRole('spinbutton').fill('0.35');
  await inherited.getByRole('checkbox').uncheck();
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.video-page-workspace')?.getAttribute('data-page-prompt-dirty')==='false');
  assert.deepEqual(saved.at(-1).changes.lora_overrides,{'motion.safetensors':{weight:.35,enabled:false}});
  assert.equal(saved.at(-1).changes.text,'树叶在微风中摇动。');
  await page.reload();await inherited.locator('summary').click();
  assert.equal(await inherited.getByRole('checkbox').isChecked(),false);
  assert.equal(await inherited.getByRole('spinbutton').inputValue(),'0.35');
  await inherited.getByRole('button',{name:'恢复继承'}).click();
  assert.equal(await inherited.getByRole('spinbutton').inputValue(),'0.6');
  assert.equal(await inherited.getByRole('checkbox').isChecked(),true);
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.video-page-workspace')?.getAttribute('data-page-prompt-dirty')==='false');
  assert.deepEqual(saved.at(-1).changes.lora_overrides,{});
  await editor.getByRole('button',{name:'添加 LoRA'}).click();
  const picker=page.getByRole('dialog',{name:'选择 LoRA'});
  await picker.getByText('H3 测试 LoRA',{exact:true}).waitFor();
  assert.equal(await picker.getByText('Anima 测试 LoRA',{exact:true}).count(),0,'按本页 H3 过滤，不能使用项目默认 Anima');
  await picker.getByRole('button',{name:'选择',exact:true}).click();
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.video-page-workspace')?.getAttribute('data-page-prompt-dirty')==='false');
  assert.deepEqual(saved.at(-1).changes.loras,[{filename:'leaf.safetensors',sha256:'b'.repeat(64),weight:.4,trigger:'leaf_motion'}]);
  await editor.locator('details').first().locator('summary').click();
  await page.screenshot({path:output+'desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>document.documentElement.scrollWidth<=window.innerWidth);
  await page.screenshot({path:output+'mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
});
