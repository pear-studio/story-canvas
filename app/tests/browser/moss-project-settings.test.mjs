import assert from 'node:assert/strict';
import {test} from 'node:test';
import {fileURLToPath} from 'node:url';
import {createServer} from 'vite';
import {chromium} from 'playwright';

test('非默认 MOSS 独立加载项目 LoRA 与描述，保存刷新、恢复和未保存保护保持一致',async()=>{
  const fixture=fileURLToPath(new URL('./fixtures/project-lora-picker.html',import.meta.url));
  const server=await createServer({root:fileURLToPath(new URL('../../',import.meta.url)),cacheDir:'../Saved/Tests/vite-moss-project-settings',optimizeDeps:{entries:[fixture],include:['react','react-dom','react-dom/client','react/jsx-runtime']},server:{host:'127.0.0.1',port:0},logLevel:'error'});
  await server.listen();
  let browser;
  try{
    browser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL??(process.platform==='win32'?'msedge':undefined)});
    const page=await browser.newPage();
    const errors=[],writes=[],profileRequests=[];
    page.on('pageerror',error=>{errors.push(error.message);console.error(error);});
    const base={style:[{id:'base-style',description:'Detailed anime illustration.'}],lighting:[]};
    const unrelated={target:'style_loras.existing',original:{exists:false},project:{exists:true,value:{filename:'existing.safetensors',weight:0.6,sha256:'a'.repeat(64)}}};
    const qwen={changes:[{target:'prompt.text',original:{exists:true,value:''},project:{exists:true,value:'Existing Qwen prompt.'}}]};
    const lora={id:'veloria-moss',name:'Veloria MOSS',file:{relative_path:'loras/veloria-moss.safetensors',sha256:'b'.repeat(64),size_bytes:100},architecture:{family:'moss-image',prompt_family:'moss-image'},base_models:[],activation:{trigger_words:['veloria'],tags:[]},recommended_generation:{weight:{default:0.6,minimum:null,maximum:null,status:'untested'},status:'untested'},source:{type:'local_training'},previews:[],examples:[]};
    let override={version:1,profiles:{qwen,'moss-image':{changes:[unrelated,{target:'prompt.style',original:{exists:true,value:base.style},project:{exists:true,value:[{id:'project-style',description:'Softly painted anime.'}]}}]}}};
    const inspection=(family)=>{
      const changes=family==='moss-image'?override.profiles['moss-image'].changes:[];
      const prompt=family==='moss-image'?{...base,...Object.fromEntries(changes.filter(change=>change.target.startsWith('prompt.')&&change.project.exists).map(change=>[change.target.slice(7),change.project.value]))}:{};
      const style_loras=Object.fromEntries(changes.filter(change=>/^style_loras\.[^.]+$/.test(change.target)&&change.project.exists).map(change=>{const id=change.target.slice('style_loras.'.length);return [id,{id,...change.project.value,available:true}];}));
      return {base_profile:{architecture_family:family},style_loras,prompt:{text:'',...prompt},project_override:{changes:changes.map(change=>({...change,label:change.target,current:change.target.startsWith('prompt.')&&Object.hasOwn(base,change.target.slice(7))?{exists:true,value:base[change.target.slice(7)]}:{exists:false}})),conflicts:[],redundant:[],blocked:false,effective_sha256:JSON.stringify(override)}};
    };
    await page.route('**/api/**',route=>{
      const url=new URL(route.request().url());
      const headers={'x-story-canvas-revision':'test-revision'};
      if(route.request().method()==='PUT'){
        assert.equal(url.pathname,'/api/projects/test/render-profile-override');
        override=route.request().postDataJSON();writes.push(structuredClone(override));
        return route.fulfill({headers,json:{saved:true,override}});
      }
      if(url.pathname.endsWith('/render-profile-override'))return route.fulfill({headers,json:{override}});
      if(url.pathname==='/api/lora-resources')return route.fulfill({json:{resources:[{status:'available',resource:lora}],raw:[],errors:[]}});
      assert.equal(url.pathname,'/api/projects/test/render-profile');
      profileRequests.push(url.searchParams.get('profile_id'));
      return route.fulfill({headers,json:{render_profiles:[{id:'qwen',name:'Qwen',architecture_family:'qwen-image-2-1',models:{},style_loras:{},errors:[],inspection:inspection('qwen-image-2-1')},{id:'moss-image',name:'MOSS',architecture_family:'moss-image',models:{},style_loras:{},errors:[],diagnosis_loaded:url.searchParams.get('profile_id')==='moss-image',inspection:url.searchParams.get('profile_id')==='moss-image'?inspection('moss-image'):null}]}});
    });
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/tests/browser/fixtures/project-lora-picker.html`);
    await page.getByLabel('LoRA 所属模型',{exact:true}).selectOption('moss-image');
    await page.getByRole('button',{name:'选择 LoRA',exact:true}).click();
    await page.getByText('Veloria MOSS',{exact:true}).waitFor();
    await page.getByRole('dialog',{name:'选择 LoRA',exact:true}).getByRole('button',{name:'选择',exact:true}).click();
    await page.getByRole('dialog',{name:'选择 LoRA',exact:true}).waitFor({state:'detached'});
    const loraCard=page.locator('.project-lora-current-list > article').filter({hasText:'veloria-moss.safetensors'});
    await loraCard.waitFor();
    assert.equal(await page.getByLabel('调整对象',{exact:true}).inputValue(),'qwen');
    assert.equal(writes.length,1);
    assert.equal(writes[0].profiles['moss-image'].changes.find(change=>change.target==='style_loras.veloria-moss').project.value.weight,0.6);
    await loraCard.getByLabel('项目权重',{exact:true}).fill('0.75');
    await loraCard.getByLabel('项目权重',{exact:true}).press('Tab');
    await page.getByRole('button',{name:'选择 LoRA',exact:true}).click();
    await page.getByRole('dialog',{name:'选择 LoRA',exact:true}).waitFor();
    assert.equal(await page.getByRole('dialog',{name:'选择 LoRA',exact:true}).getByText('Veloria MOSS',{exact:true}).count(),0);
    assert.equal(writes.length,2);
    assert.equal(writes[1].profiles['moss-image'].changes.find(change=>change.target==='style_loras.veloria-moss').project.value.weight,0.75);
    await page.getByRole('button',{name:'关闭',exact:true}).click();
    await loraCard.getByRole('button',{name:'移除',exact:true}).click();
    await loraCard.waitFor({state:'detached'});
    assert.equal(writes.length,3);
    assert.equal(writes[2].profiles['moss-image'].changes.some(change=>change.target==='style_loras.veloria-moss'),false);
    const promptWriteStart=writes.length;
    await page.getByLabel('调整对象',{exact:true}).selectOption('moss-image');
    const style=page.getByRole('textbox',{name:'画风第 1 项 Prompt',exact:true});
    await style.waitFor();
    assert.equal(await style.inputValue(),'Softly painted anime.');
    assert.ok(profileRequests.includes('moss-image'));
    assert.equal(await page.locator('.project-generation-summary__facts').getByText('Qwen',{exact:true}).isVisible(),true);
    await style.fill('Crisp anime linework.');
    await page.locator('.category-card > header').filter({has:page.getByText('光照',{exact:true})}).hover();
    await page.getByRole('button',{name:'添加光照',exact:true}).click();
    await page.getByRole('textbox',{name:'光照第 1 项 Prompt',exact:true}).fill('Warm directional sunlight.');
    await page.locator('.category-card > header').filter({has:page.getByText('避免',{exact:true})}).hover();
    await page.getByRole('button',{name:'添加避免',exact:true}).click();
    await page.getByRole('textbox',{name:'避免第 1 项 Prompt',exact:true}).fill('watermark, logo');
    await page.getByRole('button',{name:'保存项目描述',exact:true}).click();
    await page.waitForFunction(()=>!document.querySelector('[data-project-fact-dirty="true"]'));
    assert.equal(writes.length,promptWriteStart+1);
    const changes=writes[promptWriteStart].profiles['moss-image'].changes;
    assert.deepEqual(changes.find(change=>change.target==='prompt.style').original.value,base.style);
    assert.equal(changes.find(change=>change.target==='prompt.style').project.value[0].description,'Crisp anime linework.');
    assert.equal(changes.find(change=>change.target==='prompt.lighting').project.value[0].description,'Warm directional sunlight.');
    assert.equal(changes.find(change=>change.target==='prompt.avoid').project.value[0].description,'watermark, logo');
    assert.deepEqual(changes.find(change=>change.target==='prompt.avoid').original,{exists:false});
    assert.deepEqual(changes.find(change=>change.target===unrelated.target),unrelated);
    assert.deepEqual(writes[promptWriteStart].profiles.qwen,qwen);
    await page.getByRole('button',{name:'恢复画风基础值',exact:true}).click();
    await page.getByRole('button',{name:'保存项目描述',exact:true}).click();
    await page.waitForFunction(()=>!document.querySelector('[data-project-fact-dirty="true"]'));
    assert.equal(writes.length,promptWriteStart+2);
    assert.equal(writes[promptWriteStart+1].profiles['moss-image'].changes.some(change=>change.target==='prompt.style'),false);
    assert.equal(writes[promptWriteStart+1].profiles['moss-image'].changes.find(change=>change.target==='prompt.lighting').project.value[0].description,'Warm directional sunlight.');
    assert.equal(await page.getByRole('textbox',{name:'避免第 1 项 Prompt',exact:true}).inputValue(),'watermark, logo');
    await page.getByRole('button',{name:'恢复避免基础值',exact:true}).click();
    await page.getByRole('button',{name:'保存项目描述',exact:true}).click();
    await page.waitForFunction(()=>!document.querySelector('[data-project-fact-dirty="true"]'));
    assert.equal(writes.at(-1).profiles['moss-image'].changes.some(change=>change.target==='prompt.avoid'),false);
    assert.equal(await page.getByRole('textbox',{name:'避免第 1 项 Prompt',exact:true}).count(),0);
    await style.waitFor();
    assert.equal(await style.inputValue(),base.style[0].description);
    await style.fill('Unsaved draft.');
    await page.getByLabel('调整对象',{exact:true}).selectOption('qwen');
    await page.getByRole('dialog',{name:'放弃未保存的 Prompt？',exact:true}).getByRole('button',{name:'取消',exact:true}).click();
    assert.equal(await style.inputValue(),'Unsaved draft.');
    assert.equal(await page.getByLabel('调整对象',{exact:true}).inputValue(),'moss-image');
    await page.getByLabel('调整对象',{exact:true}).selectOption('qwen');
    await page.getByRole('button',{name:'放弃并继续',exact:true}).click();
    await page.getByLabel('调整对象',{exact:true}).selectOption('moss-image');
    await style.waitFor();
    assert.equal(await style.inputValue(),base.style[0].description);
    assert.equal(writes.length,promptWriteStart+3);
    assert.deepEqual(errors,[]);
  }finally{await browser?.close();await server.close();}
});
