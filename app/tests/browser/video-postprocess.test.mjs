import assert from 'node:assert/strict';
import test from 'node:test';
import {fileURLToPath} from 'node:url';
import {mkdir} from 'node:fs/promises';
import {build,preview} from 'vite';
import {chromium} from 'playwright';

test('动态页后处理：滑条与显式应用、候选切换、保存重开、失败保护和移动成品入口',async t=>{
  const output=fileURLToPath(new URL('../../../Saved/Tests/video-postprocess-ui/',import.meta.url));await mkdir(output,{recursive:true});
  const config={root:fileURLToPath(new URL('../../',import.meta.url)),build:{outDir:output+'dist',emptyOutDir:false,rollupOptions:{input:{main:fileURLToPath(new URL('./video-loras.html',import.meta.url))}}},logLevel:'error'};
  await build(config);const server=await preview({...config,preview:{host:'127.0.0.1',port:0}});
  t.after(()=>new Promise(resolve=>server.httpServer.close(resolve)));
  const browser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL||(process.platform==='win32'?'msedge':undefined)});t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1500,height:960}}),errors=[],writes=[],previews=[],cancelled=[],reports=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('requestfailed',request=>cancelled.push(request.url()));
  const heldPreviews=[];
  let heldLarge,heldSmall,holdLarge=true;
  const image={contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="640" height="480"><rect width="640" height="480" fill="#bcd1c3"/></svg>'};
  let document={title:'树叶微风',page_kind:'video'},rejectSave=false;
  const receipt=()=>({document,save:{args:{project_id:'demo',page_key:{page_id:'page-video'},section:'content',expected_sha256:'content'}}});
  const candidates=[1,2].map(n=>({candidate_id:`candidate-${n}`,seed:n,url:`/api/projects/demo/media/Outputs/pages/page-video/candidate-${n}/image.png`,video_url:`/api/projects/demo/media/Outputs/pages/page-video/candidate-${n}/video.mp4`,media_kind:'video',video:{width:640,height:480,frames:192,fps:24,duration_seconds:8,loop:false}}));
  await page.route('**/api/**',route=>route.fulfill({json:{}}));
  await page.route('**/api/performance',route=>{reports.push(route.request().postDataJSON());return route.fulfill({json:{ok:true}});});
  await page.route('**/api/agent/prompt/read',route=>route.fulfill({json:{document:{text:'树叶微风',duration:8,steps:20,reference_images:[]},save:{args:{}}}}));
  await page.route('**/api/agent/page-editor',route=>route.fulfill({json:receipt()}));
  await page.route('**/api/agent/page-editor/save',route=>{
    writes.push(route.request().postDataJSON());
    if(rejectSave)return route.fulfill({status:409,json:{error:'page_edit_conflict'}});
    document={...document,...route.request().postDataJSON().changes};return route.fulfill({json:{saved:true,...receipt()}});
  });
  await page.route('**/workbench/video-source',route=>route.fulfill({json:{sources:[],source_page_key:null,revision:'revision'}}));
  await page.route('**/workbench/page-media',route=>route.fulfill({json:{media:{candidates},revision:'revision'}}));
  await page.route('**/finished/jobs',route=>route.fulfill({json:{jobs:[]}}));
  await page.route('**/finished/output',route=>{writes.push({output:route.request().postDataJSON()});return route.fulfill({json:{job:{id:'test',page_id:'page-video',status:'completed',error:null}}});});
  await page.route('**/media/**',route=>{
    const url=new URL(route.request().url());previews.push(url);
    const speed=JSON.parse(url.searchParams.get('video_edit')||'{}').speed;
    if(speed===1.3){heldPreviews.push(route);return;}
    if(speed===1.6&&url.searchParams.get('w')==='1024')return route.fulfill({contentType:'image/webp',body:'invalid image'});
    if(speed===1.7&&url.searchParams.get('w')==='320'){heldSmall=route;return;}
    if(holdLarge&&url.searchParams.get('w')==='1024'){heldLarge=route;return;}
    return route.fulfill(image);
  });
  const open=async()=>{await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/tests/browser/video-loras.html`);await page.getByRole('tab',{name:'后处理',exact:true}).click();};
  await open();
  await page.waitForFunction(()=>!document.querySelector('.video-candidate-preview')?.disabled);
  assert.equal(await page.getByAltText('动态后处理预览').getAttribute('data-preview-width'),'320');
  await page.getByText('正在加载高清预览…',{exact:true}).waitFor();
  assert.equal(await page.getByRole('link',{name:'下载 WebP',exact:true}).count(),0,'不把小预览当成高清下载');
  assert.ok(heldLarge);
  await heldLarge.fulfill({status:503,json:{error:'video_preview_failed'}});
  await page.getByText('高清预览加载失败，当前显示小预览。',{exact:false}).waitFor();
  assert.ok(reports.some(r=>r.outcome==='failed'&&r.stage==='fetch'&&r.width===1024&&r.status===503));
  assert.equal(await page.getByAltText('动态后处理预览').isVisible(),true);
  holdLarge=false;
  await page.getByRole('button',{name:'重试预览',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('img[alt="动态后处理预览"]')?.getAttribute('data-preview-width')==='1024');
  const initialPreviews=previews.length;
  await page.getByLabel('裁掉开头（秒）',{exact:true}).fill('0.5');
  await page.getByLabel('裁掉结尾（秒）',{exact:true}).fill('1');
  await page.getByRole('slider',{name:'播放倍率滑条',exact:true}).fill('1.1');
  assert.equal(await page.getByLabel('播放倍率',{exact:true}).inputValue(),'1.1');
  await page.waitForTimeout(600);
  assert.equal(previews.length,initialPreviews,'输入与滑条不会启动编码');
  assert.ok((await page.locator('.video-candidate-list small').first().innerText()).includes('8.00 秒'),'未应用草稿不改候选显示时长');
  await page.getByRole('button',{name:'应用',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('img[alt="动态后处理预览"]')?.getAttribute('data-preview-source')?.includes('video_edit='));
  await page.getByRole('button',{name:'查看大图',exact:true}).waitFor();
  await page.waitForFunction(()=>!document.querySelector('.video-candidate-preview')?.disabled);
  const edit={trim_start_seconds:.5,trim_end_seconds:1,speed:1.1};
  assert.ok((await page.locator('.video-candidate-list small').first().innerText()).includes('5.91 秒'));
  assert.deepEqual(JSON.parse(previews.findLast(url=>url.searchParams.has('video_edit')).searchParams.get('video_edit')),edit);
  assert.equal(await page.getByRole('button',{name:'原始',exact:true}).count(),0);
  await page.getByRole('button').filter({has:page.getByAltText('视频 Seed 2',{exact:true})}).click();
  await page.waitForFunction(()=>document.querySelector('img[alt="动态后处理预览"]')?.getAttribute('data-preview-source')?.includes('candidate-2'));
  assert.equal(await page.getByLabel('播放倍率',{exact:true}).inputValue(),'1.1');
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('[data-project-fact-dirty="true"]'));
  assert.deepEqual(writes.at(-1).changes,{video_postprocess:edit});
  await open();assert.equal(await page.getByLabel('播放倍率',{exact:true}).inputValue(),'1.1');
  await page.waitForFunction(()=>document.querySelector('img[alt="动态后处理预览"]')?.getAttribute('data-preview-width')==='1024');
  rejectSave=true;await page.getByLabel('播放倍率',{exact:true}).fill('1.2');
  await page.getByRole('button',{name:'保存并输出成品',exact:true}).click();
  await page.getByText('page_edit_conflict',{exact:false}).waitFor();
  assert.equal(writes.filter(x=>x.output).length,0);
  assert.equal(await page.locator('[data-project-fact-dirty="true"]').count(),1);
  assert.equal(JSON.parse(new URL(await page.getByAltText('动态后处理预览').getAttribute('data-preview-source'),'http://localhost').searchParams.get('video_edit')).speed,1.1,'保存失败不能应用草稿');
  rejectSave=false;
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('[data-project-fact-dirty="true"]'));
  await page.waitForFunction(()=>document.querySelector('img[alt="动态后处理预览"]')?.getAttribute('data-preview-width')==='1024');
  assert.equal(JSON.parse(new URL(await page.getByAltText('动态后处理预览').getAttribute('data-preview-source'),'http://localhost').searchParams.get('video_edit')).speed,1.2,'保存自动应用，无需再点应用');
  await page.getByLabel('播放倍率',{exact:true}).fill('1.4');
  await page.getByRole('button',{name:'保存并输出成品',exact:true}).click();
  await page.waitForFunction(()=>document.body.textContent.includes('成品已输出'));
  assert.equal(writes.filter(x=>x.output).length,1);assert.equal(document.video_postprocess.speed,1.4);
  await page.getByRole('button',{name:'重置后处理',exact:true}).click();
  await page.getByRole('button',{name:'撤销',exact:true}).click();
  assert.equal(await page.getByLabel('播放倍率',{exact:true}).inputValue(),'1.4');
  await page.getByLabel('裁掉开头（秒）',{exact:true}).fill('8');
  assert.equal(await page.getByRole('button',{name:'保存并输出成品',exact:true}).isDisabled(),true);
  await page.getByRole('button',{name:'放弃修改',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('.video-candidate-preview')?.disabled);
  await page.getByLabel('播放倍率',{exact:true}).fill('1.3');
  await page.getByRole('button',{name:'应用',exact:true}).click();
  for(let n=0;n<100&&heldPreviews.length<2;n++)await page.waitForTimeout(20);
  assert.equal(heldPreviews.length,2);
  await page.getByLabel('播放倍率',{exact:true}).fill('1.5');
  await page.getByRole('button',{name:'应用',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('.video-candidate-preview')?.disabled);
  await Promise.all(heldPreviews.map(route=>route.fulfill(image).catch(()=>{})));
  for(let n=0;n<100&&!cancelled.length;n++)await page.waitForTimeout(20);
  assert.ok(cancelled.some(url=>JSON.parse(new URL(url).searchParams.get('video_edit')||'{}').speed===1.3),'再次应用会中止旧 fetch');
  assert.equal(JSON.parse(new URL(await page.getByAltText('动态后处理预览').getAttribute('data-preview-source'),'http://localhost').searchParams.get('video_edit')).speed,1.5);
  await page.getByLabel('播放倍率',{exact:true}).fill('1.6');
  await page.getByRole('button',{name:'应用',exact:true}).click();
  await page.getByText('高清预览加载失败，当前显示小预览。',{exact:false}).waitFor();
  assert.equal(await page.getByAltText('动态后处理预览').getAttribute('data-preview-width'),'320');
  assert.ok(reports.some(r=>r.outcome==='failed'&&r.stage==='decode'&&r.width===1024&&r.status===200));
  await page.getByLabel('播放倍率',{exact:true}).fill('1.7');
  await page.getByRole('button',{name:'应用',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('img[alt="动态后处理预览"]')?.getAttribute('data-preview-width')==='1024');
  assert.ok(heldSmall);await heldSmall.fulfill(image);
  await page.waitForTimeout(100);
  assert.equal(await page.getByAltText('动态后处理预览').getAttribute('data-preview-width'),'1024','迟到的小图不能降级已显示的高清图');
  await page.getByRole('button',{name:'放弃修改',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('.video-candidate-preview')?.disabled);
  await page.screenshot({path:output+'desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'候选 2',exact:true}).click();
  await page.getByRole('dialog',{name:'视频候选',exact:true}).getByRole('button',{name:'输出成品',exact:true}).waitFor();
  await page.waitForFunction(()=>!document.querySelector('.video-candidate-preview')?.disabled);
  await page.screenshot({path:output+'mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,JSON.stringify(await page.evaluate(()=>Array.from(document.querySelectorAll('body *')).filter(e=>e.getBoundingClientRect().right>innerWidth).map(e=>({tag:e.tagName,cls:e.className,width:e.getBoundingClientRect().width})))));
  const smallUrl=previews.findLast(url=>url.pathname.includes('candidate-1/video.mp4')&&url.searchParams.get('w')==='320'&&JSON.parse(url.searchParams.get('video_edit')||'{}').speed===1.4);
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/tests/browser/video-loras.html?overview=1&settings=${encodeURIComponent(JSON.stringify(document.video_postprocess))}`);
  await page.getByAltText('树叶微风最新候选图').waitFor();
  assert.equal(new URL(await page.getByAltText('树叶微风最新候选图').getAttribute('src'),smallUrl).href,smallUrl.href,'总览和页内小预览使用相同 URL 和后处理参数');
  assert.deepEqual(errors,[]);
});
